import re

# Регулярные выражения для классификации элементов документа
__all__ = ["match_element_type"]

_BULLETS = r"[-–—•·→■▪□➤*]"

REGEX_PATTERNS = {
     'heading_1': (
        r'^(?:'
        r'(?:ГЛАВА|РАЗДЕЛ|ЧАСТЬ)\s+[0-9IVXLCDM]+\s*\.?\s+[А-ЯЁA-Z][^.;:]*[^.;:\s]'
        r'|[0-9]+\.?\s+[А-ЯЁA-Z][^.;:]*[^.;:\s]'
        r'|(?:РЕФЕРАТ|СОДЕРЖАНИЕ|ТЕРМИНЫ\s+И\s+ОПРЕДЕЛЕНИЯ|'
        r'ПЕРЕЧЕНЬ\s+СОКРАЩЕНИЙ\s+И\s+ОБОЗНАЧЕНИЙ|ВВЕДЕНИЕ|ОСНОВНАЯ\s+ЧАСТЬ|'
        r'ЗАКЛЮЧЕНИЕ|СПИСОК\s+ИСПОЛЬЗОВАННЫХ\s+ИСТОЧНИКОВ|ПРИЛОЖЕНИЯ)'
        r')$'
    ),

    # ─────────────────────────── HEADING 2 ────────────────────────────
    'heading_2': r'^\d+\.\d{1,2}\s+[А-ЯЁA-Z0-9][^.;:]*[^.;:\s]$',

    # ─────────────────────────── HEADING 3 ────────────────────────────
    'heading_3': r'^\d+\.\d+\.\d+\s+[А-ЯЁA-Z0-9][^.;:]*[^.;:\s]$',

    # ─────────────────────────── HEADING 4 ────────────────────────────
    'heading_4': (
        r'^(?:'
        r'\d+\.\d+\.\d+\.\d+\s+[А-ЯЁA-Z0-9][^.;:]*[^.;:\s]|'
        r'\([A-Za-zА-Яа-яЁё]\)\s+[А-ЯЁA-Z0-9][^.;:]*[^.;:\s]|'
        r'[A-Za-zА-Яа-яЁё]\.\s+[А-ЯЁA-Z0-9][^.;:]*[^.;:\s]'
        r')$'
    ),

    # ─────────────────────────── LIST ORDERED ────────────────────────────
    'list_ordered': (
        r'^\s*(?:\d+\)|[a-zа-я]\)|[a-zа-я]\.|[IVXLCDM]+\.)\s+\S.+$'  # 1), a), а), a., а., I., II.
    ),

    # ─────────────────────────── LIST BULLET ────────────────────────────
    'list_bullet': (
        rf'^\s*(?:{_BULLETS})\s+\S.+$'  # – • ♦ Текст
    ),

    # ─────────────────────────── TABLE CAPTION ────────────────────────────
    'table_caption': (
        r'^(?:таблица|табл|table|tabl)\s*(?:\d+(?:\.\d+)*)?\s*(?:[-–—:])\s*.+$'
    ),

    # ─────────────────────────── FIGURE CAPTION ────────────────────────────
    'figure_caption': (
        r'^(?:Рисунок|Рис\.?|Figure|Fig\.?)\s+\d+(?:\.\d+)*\s*(?:–|:)\s*.+$'
    ),

    # ─────────────────────────── FORMULA ────────────────────────────
    'formula': (
        r'^(?:'
        r'(?:формула|Formula)\s+\d+(?:\.\d+)*\s*:\s*.+'
        r'|\(\d+\)\s*.+'
        r')$'
    ),
}

def match_element_type(text: str) -> str | None:
    """
    Сопоставляет текст с типом элемента на основе регулярных выражений.
    Приоритет: заголовки > списки > подписи > формулы.
    """
    for element_type, pattern in REGEX_PATTERNS.items():
        if re.match(pattern, text, flags=re.IGNORECASE):
            return element_type
    return None